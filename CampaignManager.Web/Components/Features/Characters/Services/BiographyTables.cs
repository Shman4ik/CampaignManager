    /// <summary>Бросок 1d10 по списку: возвращает номер (1–10) и текст пункта.</summary>
    public static (int Roll, string Text) Roll(IReadOnlyList<string> table)
    {
        var roll = Dice.Roll(1, table.Count);
        return (roll, table[roll - 1]);
    }
