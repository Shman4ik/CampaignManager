    public static string DurationText(InsanityBoutMode mode, int amount) =>
        mode == InsanityBoutMode.Summary
            ? $"{amount} {Plural(amount, "час", "часа", "часов")}"
            : $"{amount} {Plural(amount, "раунд", "раунда", "раундов")}";

