namespace CampaignManager.Web.Components.Features.Characters.Model;

/// <summary>
///     Строка блока «Знакомые сыщики» — шаг 11 заполнения листа («Зов Ктулху» 7e, стр. 33):
///     имя сыщика, имя его игрока и пара слов о профессии или характере.
///     <para>
///         Строки бывают двух видов. У строки состава кампании заполнен
///         <see cref="CharacterId" />: имя, игрок и профессия в ней не хранятся как данные листа,
///         а каждый раз подставляются из живого листа того сыщика — иначе переименование
///         персонажа оставляло бы у соседей по столу устаревшую копию. Своей в такой строке
///         остаётся только <see cref="Note" />.
///     </para>
///     <para>
///         У строки, вписанной руками, <see cref="CharacterId" /> пуст, и тогда всё в ней —
///         данные этого листа. Такие строки нужны листам без кампании (НПС, преген из общей
///         библиотеки) и для тех, кого за столом знают, но чьего листа в системе нет.
///     </para>
/// </summary>
public sealed class FellowInvestigator
{
    /// <summary>Лист сыщика из той же кампании (или того же сценария), если строка привязана к нему.</summary>
    public Guid? CharacterId { get; set; }

    /// <summary>Имя сыщика. У привязанной строки не используется — оно берётся из его листа.</summary>
    public string Name { get; set; } = "";

    /// <summary>Имя игрока. У привязанной строки не используется — оно берётся из его листа.</summary>
    public string PlayerName { get; set; } = "";

    /// <summary>«Пара слов о профессии или характере» — всегда своя запись владельца листа.</summary>
    public string Note { get; set; } = "";
}
