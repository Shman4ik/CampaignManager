namespace CampaignManager.Web.Components.Features.Bestiary.Model;

/// <summary>
///     Чем является строка «Бой» в статблоке существа (гл. 14, стр. 278–279).
/// </summary>
public enum CreatureAttackKind
{
    /// <summary>Обычная атака в ближнем бою — когти, щупальца, укусы, удары (стр. 278).</summary>
    Melee,

    /// <summary>Атака на расстоянии: молниемёт Старца, плевок слизью дхоула.</summary>
    Ranged,

    /// <summary>
    ///     Манёвр — захват, затаптывание, сбивание с ног. Книга помечает такие строки
    ///     «(манёвр)»; существо совершает их навыком Ближний бой, а исход решает разница
    ///     Комплекции, а не урон (стр. 279).
    /// </summary>
    Maneuver,

    /// <summary>
    ///     Особая атака, которая не сводится к броску урона: поглощение шоггота,
    ///     гипнотический взгляд вампира, вытягивание характеристик. Разрешается
    ///     встречной проверкой или отдельным правилом из описания.
    /// </summary>
    Special
}
