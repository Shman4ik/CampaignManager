namespace CampaignManager.Web.Components.Features.Combat.Model;

/// <summary>
/// Насколько цель готова к атаке (CoC 7e, «Ударить первым», стр. 104–105).
/// </summary>
public enum SurpriseMode
{
    /// <summary>
    /// Цель начеку: сама выбирает, уклоняться или контратаковать. Обычная встречная проверка.
    /// </summary>
    TargetReady = 0,

    /// <summary>
    /// Цель не готова, и Хранитель решил, что атака проходит автоматически —
    /// например, удар по голове незамеченным противником. Бросок атаки всё равно
    /// выполняется, но провалом считается только крах. Для дистанционных атак
    /// правила этого не допускают: бросок на попадание нужен всегда.
    /// </summary>
    AutoHit = 1,

    /// <summary>
    /// Цель не готова, но исход не предрешён — например, попытка вырвать оружие.
    /// Атакующий получает бонусную кость, цель не защищается.
    /// </summary>
    BonusDie = 2
}
