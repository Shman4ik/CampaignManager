namespace CampaignManager.Web.Components.Features.Combat.Model;

/// <summary>
/// Режим стрельбы (CoC 7e, стр. 111–114). Определяет, сколько патронов уходит
/// на одну проверку атаки и какие штрафы к ней применяются.
/// </summary>
public enum FiringMode
{
    /// <summary>Одиночный выстрел — обычная проверка без штрафа за скорострельность.</summary>
    Single = 0,

    /// <summary>
    /// Серия выстрелов из пистолета: 2–3 пули за раунд, отдельная проверка на каждый
    /// выстрел, все со штрафной костью (стр. 111).
    /// </summary>
    PistolBurst = 1,

    /// <summary>
    /// Очередь или залп автоматического оружия. Одна проверка на залп; каждая
    /// следующая проверка в раунде получает дополнительную штрафную кость,
    /// а после двух — повышает уровень сложности (стр. 114).
    /// </summary>
    Volley = 2
}
